import { expect, test } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { createChecklist, criterion, draft, servers, tmpDir, uid } from './support';

test('AI criterion remains a draft until human weight, mapping confirmation and version save', async ({ page, request }) => {
  const original = await createChecklist(request, servers.complete, draft(uid('Учебный редактор'), [criterion('existing', { title: 'Существующее правило' })]));
  const before = await (await request.get(`${servers.complete}/api/v1/checklist-versions/${original.version_id}`)).json();
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.goto(`/#/checklists/${original.checklist_id}/edit?from=${original.version_id}`);
  await page.getByText('✦ Создать критерий с помощью ИИ', { exact: true }).click();
  const panel = page.locator('.criterion-designer');
  await panel.getByLabel('Название будущего критерия').fill('Понятный следующий шаг');
  await panel.getByLabel('Какое действие нужно оценить — одной фразой').fill('Оператор объясняет, что клиенту делать дальше.');
  await panel.getByRole('button', { name: 'Предложить правило и шкалу', exact: true }).click();
  await expect(panel.getByRole('region', { name: 'Предложение критерия' })).toContainText('Тестовая подсказка · не AI-анализ');
  let versions = await (await request.get(`${servers.complete}/api/v1/checklists/${original.checklist_id}/versions`)).json();
  expect(versions.total).toBe(1);
  const screenshots = path.join(tmpDir, 'criterion-designer'); fs.mkdirSync(screenshots, { recursive: true });
  await panel.getByRole('region', { name: 'Предложение критерия' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(screenshots, 'laptop.png') });
  await panel.getByRole('button', { name: 'Добавить в черновик', exact: true }).click();
  const editor = page.getByTestId('editor-criterion');
  await expect(editor.getByLabel('Название', { exact: true })).toHaveValue('Понятный следующий шаг');
  await expect(editor.getByLabel('Вес', { exact: true })).toHaveValue('');
  await page.getByRole('button', { name: 'Сохранить как новую версию', exact: true }).click();
  await expect(editor).toContainText('Проверьте и подтвердите предложенные AI доли шкалы.');
  await editor.getByLabel('Вес', { exact: true }).fill('15');
  await editor.getByRole('checkbox', { name: 'Подтверждаю предложенные AI доли шкалы', exact: true }).check();
  await page.setViewportSize({ width: 390, height: 844 });
  await editor.scrollIntoViewIfNeeded();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(screenshots, 'narrow.png') });
  await page.getByRole('button', { name: 'Сохранить как новую версию', exact: true }).click();
  await expect(page.getByTestId('version-saved')).toBeVisible();
  versions = await (await request.get(`${servers.complete}/api/v1/checklists/${original.checklist_id}/versions`)).json();
  expect(versions.total).toBe(2);
  expect(versions.items[0].criteria).toHaveLength(2);
  expect(versions.items[0].criteria[0]).toEqual(before.criteria[0]);
  expect(versions.items[0].criteria[1].weight).toBe('15');
  expect(await (await request.get(`${servers.complete}/api/v1/checklist-versions/${original.version_id}`)).json()).toEqual(before);
});
