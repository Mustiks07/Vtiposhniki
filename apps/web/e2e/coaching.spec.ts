import { expect, test } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { createChecklist, criterion, draft, evaluation, importViaApi, record, runBatchApi, servers, tmpDir, uid } from './support';

test('coaching appears below the operator message, keeps scores and separates scope', async ({ page, request }) => {
  const c = criterion('closing', { title: 'Завершение разговора' });
  c.choices.reverse();
  const version = await createChecklist(request, servers.complete, draft(uid('Учебный коучинг'), [c]));
  const imported = await importViaApi(request, servers.complete, [record(uid('coaching'))]);
  const batch = await runBatchApi(request, servers.complete, [imported.items[0].conversation_id], version.version_id);
  const eid = batch.jobs[0].evaluation_id!;
  const before = await evaluation(request, servers.complete, eid);
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.goto(`/#/evaluations/${eid}?criterion=closing&scope=effective`);
  await page.getByRole('button', { name: 'Как надо было сказать', exact: true }).click();
  const inline = page.locator('[data-message-id="m0002"] .coaching-inline');
  await expect(inline).toBeVisible();
  await expect(inline).toContainText('Тестовая подсказка · не AI-анализ');
  await expect(inline).toContainText('[нужные сведения компании]');
  await expect(inline).toContainText('test-coaching');
  expect(await evaluation(request, servers.complete, eid)).toEqual(before);
  const screenshots = path.join(tmpDir, 'coaching');
  fs.mkdirSync(screenshots, { recursive: true });
  await inline.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(screenshots, 'laptop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await inline.scrollIntoViewIfNeeded();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(screenshots, 'narrow.png') });
  await page.reload();
  await expect(inline).toBeVisible();
  await page.goto(`/#/evaluations/${eid}?criterion=closing&scope=automatic`);
  await expect(page.getByRole('button', { name: 'Как надо было сказать', exact: true })).toBeVisible();
  await expect(page.locator('.coaching-inline')).toHaveCount(0);
  const history = await (await request.get(`${servers.complete}/api/v1/evaluations/${eid}/assistant-runs`)).json();
  expect(history.total).toBe(1);
  expect(history.items[0].calls).toHaveLength(1);
});
