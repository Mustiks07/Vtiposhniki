import { expect, test } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { createChecklist, criterion, draft, evaluation, importViaApi, record, runBatchApi, servers, tmpDir, uid } from './support';

test('conversation assistant cites transcript and refuses unrelated questions without changing evaluation', async ({ page, request }) => {
  const version = await createChecklist(request, servers.complete, draft(uid('Вопросы AI'), [criterion('help')]));
  const imported = await importViaApi(request, servers.complete, [record(uid('assistant'))]);
  const batch = await runBatchApi(request, servers.complete, [imported.items[0].conversation_id], version.version_id);
  const eid = batch.jobs[0].evaluation_id!;
  const before = await evaluation(request, servers.complete, eid);
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.goto(`/#/evaluations/${eid}`);
  await page.getByText('✦ Спросить AI про этот разговор', { exact: true }).click();
  const panel = page.locator('.conversation-assistant');
  await panel.getByLabel('Вопрос о разговоре или оценке').fill('Что ответил оператор?');
  await panel.getByRole('button', { name: 'Спросить AI', exact: true }).click();
  await expect(panel.getByTestId('conversation-answer')).toHaveCount(1);
  await expect(panel.getByTestId('conversation-answer')).toContainText('Тестовая подсказка · не AI-анализ');
  await panel.getByRole('button', { name: 'Реплика 2', exact: true }).click();
  await expect(page.locator('[data-message-id="m0002"]')).toHaveAttribute('data-highlighted', 'true');
  await panel.getByLabel('Вопрос о разговоре или оценке').fill('Какая завтра погода?');
  await panel.getByRole('button', { name: 'Спросить AI', exact: true }).click();
  await expect(panel.getByTestId('conversation-answer')).toHaveCount(2);
  const refusal = panel.getByTestId('conversation-answer').filter({ hasText: 'Какая завтра погода?' });
  await expect(refusal).toContainText('Вопрос не относится к разговору');
  await expect(refusal.getByRole('button', { name: /Реплика/ })).toHaveCount(0);
  await refusal.getByText('Вызовы и расход подсказки', { exact: true }).click();
  await expect(refusal.locator('tbody tr')).toHaveCount(1);
  await expect(refusal.locator('tbody')).toContainText('0 USD');
  expect(await evaluation(request, servers.complete, eid)).toEqual(before);
  const screenshots = path.join(tmpDir, 'conversation-assistant'); fs.mkdirSync(screenshots, { recursive: true });
  await refusal.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(screenshots, 'laptop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('tab', { name: 'Оценка', exact: true }).click();
  await refusal.scrollIntoViewIfNeeded();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(screenshots, 'narrow.png') });
  await page.reload();
  await page.getByText('✦ Спросить AI про этот разговор', { exact: true }).click();
  await expect(panel.getByTestId('conversation-answer')).toHaveCount(2);
});
